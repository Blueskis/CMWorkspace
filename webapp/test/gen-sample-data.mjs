/**
 * Generate webapp/src/sample-data.js from the user's real (metadata-stripped) template
 * and FSD, so the published artifact can offer them as a "use sample files" quick-start
 * for users whose organisation blocks direct file uploads.
 *
 * This is a one-off generator, not part of the shipped pipeline — re-run it by hand
 * whenever the source files change:
 *
 *   node test/gen-sample-data.mjs
 *
 * Inputs live outside the repo (the user's real content, kept in the gitignored
 * training/ workspace and the session's ephemeral upload directory) — the generated
 * output (sample-data.js) is itself gitignored for the same reason: it embeds real
 * content, not a fixture other clones of this repo should carry.
 */
import { readFileSync, writeFileSync } from "node:fs";

const TEMPLATE_PATH = "../training/supplier-block-unblock-20260829/Training_Material_Template_stripped.pptx";
const TEMPLATE_NAME = "Training_Material_Template.pptx";
const FSD_PATH = "/root/.claude/uploads/29ef6b33-98cd-5a1e-bc57-1282a5387088/90bd702a-FSD_MMWA014_Supplier_Block_Unblock.docx";
const FSD_NAME = "FSD_MMWA014_Supplier_Block_Unblock.docx";

const templateB64 = readFileSync(TEMPLATE_PATH).toString("base64");
const fsdB64 = readFileSync(FSD_PATH).toString("base64");

const out = `/**
 * Generated by webapp/test/gen-sample-data.mjs — do not hand-edit.
 *
 * Embeds the user's real template (with identity metadata stripped by
 * training/supplier-block-unblock-20260829/_strip_template_metadata.py — see that
 * script's docstring for exactly what was removed and why) and their real FSD (whose own
 * metadata was checked and found to carry nothing identifying) so the published artifact
 * can offer them as a one-click "use sample files" option for users who cannot upload
 * files directly (e.g. a locked-down corporate laptop).
 */

export const SAMPLE_TEMPLATE = {
  filename: ${JSON.stringify(TEMPLATE_NAME)},
  mimeType: "application/vnd.openxmlformats-officedocument.presentationml.presentation",
  base64: ${JSON.stringify(templateB64)},
};

export const SAMPLE_FSD = {
  filename: ${JSON.stringify(FSD_NAME)},
  mimeType: "application/vnd.openxmlformats-officedocument.wordprocessingml.document",
  base64: ${JSON.stringify(fsdB64)},
};
`;

writeFileSync("src/sample-data.js", out);
console.log(
  `wrote src/sample-data.js: template ${(templateB64.length / 1024).toFixed(0)} KiB b64, ` +
    `fsd ${(fsdB64.length / 1024).toFixed(0)} KiB b64`
);

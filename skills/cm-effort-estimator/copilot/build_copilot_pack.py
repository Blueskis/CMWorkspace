#!/usr/bin/env python3
"""Build the Microsoft 365 Copilot pack for the CM Effort Estimator.

Everything is generated from ../estimator.html, the artifact's own source, so
the Copilot agent, its skill script, its knowledge files and the Excel
workbook can never drift from the published estimator:

    dist/cm-effort-estimator-skill.zip   upload under Configure > Skills
    dist/knowledge/*.csv                 upload under Configure > Knowledge
    dist/CM-Effort-Estimator.xlsx        the formula engine and the record
    skill/cm-effort-estimator/           the unzipped skill, for review

Run from anywhere:  python3 build_copilot_pack.py
Needs: node (to run the engine once for its reference data), openpyxl.
"""

import csv
import json
import shutil
import subprocess
import sys
import zipfile
from pathlib import Path

HERE = Path(__file__).resolve().parent
SOURCE = HERE.parent / "estimator.html"
SKILL_DIR = HERE / "skill" / "cm-effort-estimator"
DIST = HERE / "dist"

ENGINE_START = "// ---- engine start ----"
ENGINE_END = "// ---- engine end ----"
JUDGEMENT_START = "// ---- judgement start ----"
JUDGEMENT_END = "// ---- judgement end ----"


def slice_between(text, start, end):
    a, b = text.find(start), text.find(end)
    if a < 0 or b < 0 or b < a:
        sys.exit(f"marker missing or out of order: {start} / {end}")
    return text[a + len(start):b]


def build_engine():
    html = SOURCE.read_text(encoding="utf-8")
    engine = slice_between(html, ENGINE_START, ENGINE_END)
    judgement = slice_between(html, JUDGEMENT_START, JUDGEMENT_END)
    cli = (HERE / "src" / "cli.js").read_text(encoding="utf-8")
    out = "\n".join([
        "// CM Effort Estimator engine for the Microsoft 365 Copilot skill.",
        "// GENERATED by build_copilot_pack.py from estimator.html. Do not edit by hand:",
        "// change estimator.html or src/cli.js and rebuild, so the artifact and the",
        "// Copilot agent always run the same code.",
        '"use strict";',
        "// The engine persists to localStorage in the browser; here state travels",
        "// as JSON in and out instead, so storage is a no-op.",
        "const localStorage = { getItem() { return null; }, setItem() {}, removeItem() {} };",
        "(function () {",
        engine,
        judgement,
        cli,
        "})();",
        "",
    ])
    target = SKILL_DIR / "scripts" / "engine.js"
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(out, encoding="utf-8")
    return target


def run_engine(engine_path, command, payload=None):
    proc = subprocess.run(["node", str(engine_path), command], input=json.dumps(payload or {}),
                          capture_output=True, text=True, check=False)
    if proc.returncode != 0:
        sys.exit(f"engine {command} failed: {proc.stdout}{proc.stderr}")
    return json.loads(proc.stdout)


def write_knowledge(data):
    kdir = DIST / "knowledge"
    kdir.mkdir(parents=True, exist_ok=True)
    tasks_by_group = {}
    for t in data["tasks"]:
        tasks_by_group.setdefault(t["g"], []).append(t["t"])

    with open(kdir / "catalogue.csv", "w", newline="", encoding="utf-8") as f:
        w = csv.writer(f)
        w.writerow(["catalogue_id", "global_line_id", "local_line_id", "deliverable", "category", "unit",
                    "quantity_rule", "core_scope", "mode_of_conduct_applies", "tasks"])
        modes = set(data["modeApplies"])
        for c in data["catalogue"]:
            w.writerow([c["id"], f"global:{c['id']}", f"local:{c['id']}", c["name"], c["cat"], c["unit"], c["qty"],
                        "yes" if c["core"] else "no", "yes" if c["id"] in modes else "no",
                        "; ".join(tasks_by_group.get(c["id"], []))])

    with open(kdir / "drivers-and-levers.csv", "w", newline="", encoding="utf-8") as f:
        w = csv.writer(f)
        w.writerow(["lever", "op", "target", "allowed_values", "default", "meaning"])
        for d in data["drivers"]:
            allowed = " | ".join(str(o[0]) for o in d["options"]) if d["options"] else "number >= 0"
            w.writerow([d["label"], "set_driver", d["key"], allowed, d["def"], "Scope driver"])
        meanings = {
            "involvement.global": "Our share of the global build, %",
            "involvement.local": "Our share of the local build, %",
            "reviewCycles": "Rounds of client review plus our QA",
            "localisationFactor": "Effort to adapt a global deliverable per market, % of build",
            "contingency": "Delivery buffer, % of effort",
        }
        for t, (lo, hi) in data["judgementGlobals"].items():
            w.writerow([meanings[t], "set_global", t, f"{lo} to {hi}", "", "Global setting"])
        w.writerow(["Line complexity", "set_line_level", "<line id>", "Simple | Standard | Complex", "", ""])
        w.writerow(["Line mode of conduct", "set_line_mode", "<line id>", "virtual | blended | physical",
                    "", "Sessions and workshops only"])
        w.writerow(["Line quantity", "set_line_qty", "<line id>", "number >= 0", "", ""])
        w.writerow(["Line in scope", "set_line_include", "<line id>", "true | false", "", ""])
        w.writerow(["Line priced as option", "set_line_optional", "<line id>", "true | false", "", ""])
        w.writerow(["New deliverable", "add_line", "global | local", "{name, qty, level, archetype}", "", ""])
        w.writerow(["Assumption only", "note", "", "", "", "Moves no number"])

    with open(kdir / "hours-library.csv", "w", newline="", encoding="utf-8") as f:
        w = csv.writer(f)
        w.writerow(["catalogue_id", "task", "unit", "archetype", "graded_complexity", "hours"])
        for t in data["tasks"]:
            w.writerow([t["g"], t["t"], t["u"], t["a"], t["c"], t["h"]])


def zip_skill():
    shutil.copy(HERE / "src" / "SKILL.md", SKILL_DIR / "SKILL.md")
    DIST.mkdir(parents=True, exist_ok=True)
    target = DIST / "cm-effort-estimator-skill.zip"
    with zipfile.ZipFile(target, "w", zipfile.ZIP_DEFLATED) as z:
        for p in sorted(SKILL_DIR.rglob("*")):
            if p.is_file():
                z.write(p, p.relative_to(SKILL_DIR))
    return target


def recalc_workbook(book):
    """Store computed values so the workbook shows numbers before Excel recalculates.

    Uses the xlsx skill's LibreOffice helper when present (XLSX_RECALC overrides the
    path). Without it the workbook is still correct: Excel computes on open.
    """
    import os
    recalc = Path(os.environ.get("XLSX_RECALC", "/mnt/skills/public/xlsx/scripts/recalc.py"))
    if not recalc.exists() or not shutil.which("soffice"):
        print("note: LibreOffice recalc unavailable; workbook ships without cached values", file=sys.stderr)
        return
    res = subprocess.run([sys.executable, str(recalc), str(book), "300"], capture_output=True, text=True,
                         cwd=str(recalc.parent))
    status = json.loads(res.stdout or "{}")
    if status.get("status") != "success":
        sys.exit(f"workbook recalculation failed: {res.stdout}{res.stderr}")


def main():
    engine = build_engine()
    data = run_engine(engine, "data")
    st = run_engine(engine, "selftest")
    if not st.get("ok"):
        sys.exit(f"engine selftest failed: {st}")
    (SKILL_DIR / "SKILL.md").parent.mkdir(parents=True, exist_ok=True)
    write_knowledge(data)
    skill_zip = zip_skill()

    samples = DIST / "samples"
    samples.mkdir(parents=True, exist_ok=True)
    (samples / "public-authority-rfp.txt").write_text(data["samples"]["publicAuthority"], encoding="utf-8")
    (samples / "rail-operator-rfp.txt").write_text(data["samples"]["transport"], encoding="utf-8")

    sys.path.insert(0, str(HERE))
    from workbook import build_workbook  # noqa: E402
    book = build_workbook(data, DIST / "CM-Effort-Estimator.xlsx")
    recalc_workbook(book)

    print(json.dumps({"engine": str(engine), "selftest": st, "skill": str(skill_zip), "workbook": str(book)}, indent=2))


if __name__ == "__main__":
    main()
